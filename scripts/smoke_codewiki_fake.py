#!/usr/bin/env python3
"""Offline smoke test for CodeWiki's generation pipeline.

This runs the real CodeWiki dependency analysis and DocumentationGenerator,
but replaces the LLM backend with a deterministic fake. It does not read
~/.codewiki, does not call an API, and does not need any API key.

Two scenarios are exercised:

* whole-repository mode (small repo, no clustering call)
* clustered mode (forced tiny token threshold; fake clustering + per-module docs)

Run with the CodeWiki venv:

    .venv-codewiki/bin/python scripts/smoke_codewiki_fake.py

Artifacts are kept under `runs/smoke-codewiki/{whole,cluster}/`.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import shutil
from pathlib import Path

from codewiki.src.be.backend import LLMBackend
from codewiki.src.be.doc_layout import module_doc_relpath
from codewiki.src.be.documentation_generator import DocumentationGenerator
from codewiki.src.config import Config

ROOT = Path(__file__).resolve().parent.parent


class FakeBackend(LLMBackend):
    """Deterministic backend for the smoke test; no network or API key."""

    def __init__(self) -> None:
        self.complete_calls: list[str] = []
        self.module_calls: list[tuple[str, list[str]]] = []

    def complete(
        self, prompt: str, *, model: str | None = None, system_prompt: str | None = None
    ) -> str:
        self.complete_calls.append(prompt[:160])
        self._record_usage(
            "complete",
            "smoke",
            {"input_tokens": 12, "output_tokens": 6},
            model="fake-codewiki-model",
        )
        if "<POTENTIAL_CORE_COMPONENTS>" in prompt:
            # Clustered scenario: group the leaf component IDs by source file.
            section = prompt.split("<POTENTIAL_CORE_COMPONENTS>", 1)[1].split(
                "</POTENTIAL_CORE_COMPONENTS>", 1
            )[0]
            groups: dict[str, dict] = {}
            for line in section.splitlines():
                if not line.startswith("\t"):
                    continue
                component_id = line.strip()
                if "::" not in component_id:
                    continue
                relative_path = component_id.split("::", 1)[0]
                module_name = Path(relative_path).stem
                group = groups.setdefault(
                    module_name, {"path": relative_path, "components": []}
                )
                group["components"].append(component_id)
            return "<GROUPED_COMPONENTS>\n" + repr(groups) + "\n</GROUPED_COMPONENTS>"

        # Parent / repository overview completion.
        return (
            "<OVERVIEW># Overview\n\n"
            "Deterministic fake overview for the offline CodeWiki smoke test.\n"
            "</OVERVIEW>"
        )

    async def run_module_agent(
        self,
        module_name,
        components,
        core_component_ids,
        module_path,
        working_dir,
    ):
        self.module_calls.append((module_name, list(module_path)))
        tree_path = Path(working_dir) / "module_tree.json"
        tree = (
            json.loads(tree_path.read_text(encoding="utf-8"))
            if tree_path.is_file()
            else {}
        )

        if module_path:
            rel = module_doc_relpath(module_path, "flat")
            page = Path(working_dir) / rel
        else:
            # Whole-repository mode: CodeWiki renames <repo-name>.md to overview.md.
            page = Path(working_dir) / f"{module_name}.md"
        page.parent.mkdir(parents=True, exist_ok=True)
        page.write_text(
            f"# {module_name}\n\n"
            "Offline smoke documentation generated by FakeBackend.\n\n"
            f"Components: {len(core_component_ids)}\n",
            encoding="utf-8",
        )
        self._record_usage(
            "module_agent",
            module_name,
            {"input_tokens": 100, "output_tokens": 50},
            model="fake-codewiki-model",
        )
        return tree


def make_toy_repo(repo: Path) -> None:
    repo.mkdir(parents=True, exist_ok=True)
    (repo / "calculator.py").write_text(
        '"""Tiny calculator used by the CodeWiki smoke test."""\n\n'
        "def add(a: int, b: int) -> int:\n"
        '    """Return a + b."""\n'
        "    return a + b\n\n"
        "def multiply(a: int, b: int) -> int:\n"
        '    """Return a * b."""\n'
        "    return a * b\n",
        encoding="utf-8",
    )
    (repo / "app.py").write_text(
        '"""Tiny command-line entry point."""\n\n'
        "from calculator import add, multiply\n\n"
        "def run() -> int:\n"
        '    """Run one deterministic calculation."""\n'
        "    return multiply(add(1, 2), 3)\n",
        encoding="utf-8",
    )


def run_scenario(root: Path, mode: str) -> dict:
    out = root / mode
    docs = out / "docs"
    repo = out / "repo"
    make_toy_repo(repo)

    # Whole-repo mode: a huge clustering threshold makes CodeWiki document the
    # repository in one agent run. Clustered mode: threshold=1 forces the real
    # clustering code path, fed by the fake `<GROUPED_COMPONENTS>` response.
    threshold = 10_000_000 if mode == "whole" else 1
    config = Config(
        repo_path=str(repo),
        output_dir=str(docs / "temp"),
        dependency_graph_dir=str(docs / "temp" / "dependency_graphs"),
        docs_dir=str(docs),
        max_depth=2,
        llm_base_url="http://127.0.0.1:9/v1",
        llm_api_key="offline-smoke-no-key",
        main_model="fake-codewiki-model",
        cluster_model="fake-codewiki-model",
        fallback_model="fake-codewiki-model",
        provider="openai-compatible",
        max_token_per_module=threshold,
        min_token_per_module=1,
        artifacts_enabled=False,
        with_prose=False,
        use_gitignore=False,
        layout="flat",
        max_tokens=8192,
    )

    backend = FakeBackend()
    generator = DocumentationGenerator(config, backend=backend)
    print(f"\n[{mode}] repo={repo}")
    print(f"[{mode}] docs={docs}")
    asyncio.run(generator.run())

    metadata = json.loads((docs / "metadata.json").read_text(encoding="utf-8"))
    pages = sorted(p.relative_to(docs).as_posix() for p in docs.rglob("*.md"))
    graphs = sorted(
        (docs / "temp" / "dependency_graphs").glob("*_dependency_graph.json")
    )
    tree = json.loads((docs / "module_tree.json").read_text(encoding="utf-8"))

    result = {
        "mode": mode,
        "pages": pages,
        "module_tree": tree,
        "dependency_graphs": [str(p.relative_to(docs)) for p in graphs],
        "complete_calls": len(backend.complete_calls),
        "module_calls": len(backend.module_calls),
        "usage_calls": metadata.get("usage", {}).get("n_calls", 0),
        "files_generated": metadata.get("files_generated", []),
    }
    print(
        f"[{mode}] pages={pages} modules={len(tree)} "
        f"calls(complete={result['complete_calls']}, module={result['module_calls']})"
    )

    assert (docs / "overview.md").is_file(), f"[{mode}] overview.md missing"
    assert (docs / "overview.md").read_text(encoding="utf-8").strip(), (
        f"[{mode}] empty overview"
    )
    assert (docs / "metadata.json").is_file(), f"[{mode}] metadata.json missing"
    assert graphs, f"[{mode}] dependency graph missing"
    assert backend.module_calls, f"[{mode}] fake module agent not called"
    assert result["usage_calls"] > 0, f"[{mode}] usage ledger empty"
    if mode == "whole":
        assert not tree, f"[{mode}] expected whole-repository (empty) module tree"
        assert result["complete_calls"] == 0, f"[{mode}] unexpected completion call"
    else:
        assert tree, f"[{mode}] expected a clustered module tree"
        assert len(tree) >= 2, f"[{mode}] expected at least two modules, got {tree}"
        assert result["complete_calls"] >= 2, (
            f"[{mode}] expected clustering + overview calls"
        )
        for page in pages:
            assert page != "overview.md" or page in pages
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=ROOT / "runs" / "smoke-codewiki",
        help="artifact directory (default: runs/smoke-codewiki)",
    )
    parser.add_argument(
        "--keep",
        action="store_true",
        help="keep an existing output directory instead of recreating it",
    )
    args = parser.parse_args()

    out = args.output_dir.resolve()
    if out.exists() and not args.keep:
        shutil.rmtree(out)
    out.mkdir(parents=True, exist_ok=True)

    results = [run_scenario(out, "whole"), run_scenario(out, "cluster")]
    (out / "smoke-result.json").write_text(
        json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
    )
    print(f"\nWrote {out / 'smoke-result.json'}")
    print("OK: CodeWiki offline smoke test passed in both modes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
